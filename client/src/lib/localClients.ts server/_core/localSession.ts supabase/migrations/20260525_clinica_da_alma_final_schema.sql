-- Políticas de negação explícita para anon/authenticated direto. O backend com service_role ignora RLS.
do $$
declare
  tbl text;
begin
  foreach tbl in array array[
    'users','therapeutic_spaces','clients','therapeutic_records','sessions','appointments',
    'emotional_evolution','therapist_observations','protocols','meditations','audio_files',
    'client_meditations','treatment_evolution','uploads','financial_records'
  ] loop
    execute format('drop policy if exists "deny_direct_client_access" on public.%I', tbl);
    execute format('create policy "deny_direct_client_access" on public.%I for all to anon, authenticated using (false) with check (false)', tbl);
  end loop;
end $$;

drop policy if exists "deny_direct_storage_access" on storage.objects;
create policy "deny_direct_storage_access"
on storage.objects for all to anon, authenticated
using (bucket_id <> 'clinica-da-alma-files')
with check (bucket_id <> 'clinica-da-alma-files');

