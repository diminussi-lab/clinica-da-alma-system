-- Clínica da Alma — schema Supabase definitivo
-- Execute este arquivo no SQL Editor do Supabase ou via Supabase CLI.
-- Ele cria a base persistente para clientes, espaços terapêuticos, sessões,
-- prontuários, histórico emocional/energético, observações, protocolos,
-- meditações, uploads e registros financeiros.

create extension if not exists pgcrypto;

-- Tipos de domínio
create type if not exists public.user_role as enum ('user', 'admin');
create type if not exists public.session_type as enum ('individual', 'group', 'online');
create type if not exists public.appointment_status as enum ('scheduled', 'completed', 'cancelled', 'no-show');
create type if not exists public.audio_type as enum ('meditation', 'session_recording', 'personal_note', 'protocol_audio', 'other');
create type if not exists public.protocol_status as enum ('active', 'paused', 'completed', 'archived');
create type if not exists public.meditation_difficulty as enum ('beginner', 'intermediate', 'advanced');
create type if not exists public.financial_record_type as enum ('income', 'expense');
create type if not exists public.upload_kind as enum ('document', 'image', 'audio', 'video', 'report', 'contract', 'other');

-- Atualização automática de updated_at
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- Usuários/terapeutas do sistema. Mantém compatibilidade com o app atual,
-- mas sem dependência de Manus Auth.
create table if not exists public.users (
  id bigint generated by default as identity primary key,
  open_id text not null unique,
  name text,
  email text unique,
  login_method text default 'local' not null,
  password_hash text,
  role public.user_role default 'admin' not null,
  created_at timestamptz default now() not null,
  updated_at timestamptz default now() not null,
  last_signed_in timestamptz default now() not null
);

create trigger users_set_updated_at
before update on public.users
for each row execute function public.set_updated_at();

-- Áreas/espaços terapêuticos: salas, espaços online, unidades ou linhas de atendimento.
create table if not exists public.therapeutic_spaces (
  id bigint generated by default as identity primary key,
  therapist_id bigint not null references public.users(id) on delete cascade,
